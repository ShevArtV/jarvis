"""Пачка уведомлений QW → ход основного диалога Тимлида: gate по одному, потом дайджест.

Один поток: Тимлид сам спрашивает оператора, сам исполняет решение и отдаёт
работу субагентам, а их отчёты приходят в тот же диалог. Ход идёт отдельным
(exclusive) ходом живого процесса — довеском к чужому ходу он не встаёт.
"""

from __future__ import annotations

# Сколько ждать ответа оператора на один gate. Не ответил — остальные gate
# уходят в дайджест списком, вопросы больше не задаются.
GATE_ASK_TIMEOUT_SECONDS = 1200
# Ход живого процесса обрывается по CLAUDE_TIMEOUT (час) вместе с ожиданием
# ask_user, поэтому все вопросы раунда укладываются в этот бюджет.
ROUND_ASK_BUDGET_MINUTES = 40


def build_round_prompt(events: list[str]) -> str:
    parts = [
        f"[Пачка уведомлений QueueWarden (канал «Бот»), {len(events)} шт., "
        "от старых к новым. Это не сообщение оператора.]",
    ]
    parts += [f"--- {n} ---\n{text}" for n, text in enumerate(events, 1)]
    parts.append(
        "Разбери пачку в два шага.\n\n"
        "Шаг 1 — gate. Сверь каждую задачу пачки с текущим состоянием через MCP её "
        "установки (queuewarden_task_get; сервер другой установки задачу не найдёт). "
        "Gate — только реальный pending в `approvals`, который оператор не отложил "
        "(`postponed_at` пуст). Порядок — «Очередь фокуса» QW: queuewarden_task_query "
        "с status: \"open\" и sortBy: \"focus\", место — focus_position; установка не "
        "знает sortBy=focus — `~/projects/knowledge-base/bin/task-queue.py`.\n"
        "По каждому gate — один вызов ask_user, следующий только после ответа на "
        "текущий. В вопросе: контекст задачи; для плана — суть, риски, альтернатива, "
        "приоритет, дедлайн и место в очереди (не следующая — кого обгоняет); мнение "
        "Тимлида; строки «Сайт: <url из строки Ссылка>» и «Миниапп: <url из строки "
        "Миниапп>», если они есть в уведомлении. options: «Принять», «Отклонить», "
        f"«Отложить решение»; timeout_seconds={GATE_ASK_TIMEOUT_SECONDS}.\n"
        "Ответ оператора исполни сразу: queuewarden_decide_approval (decision строго "
        "approved или rejected, у rejected — непустой comment) или "
        "queuewarden_postpone_approval. Работа, которая нужна после решения, — "
        "фоновому субагенту; его не жди, переходи к следующему gate.\n"
        "Оператор не ответил за отведённое время — больше не спрашивай: оставшиеся "
        "gate уходят в дайджест. Время раунда ограничено: в начале хода запомни "
        "время (`date`), вопросы задавай только первые "
        f"{ROUND_ASK_BUDGET_MINUTES} минут хода, и timeout_seconds каждого вопроса — "
        "не больше остатка этого времени; вышло — оставшиеся gate в дайджест. Если по твоим правилам gate сейчас решаешь ты "
        "(ночная смена) — решай сам, без ask_user.\n\n"
        "Шаг 2 — дайджест, ответом этого хода:\n"
        "- первая строка: сколько уведомлений и за какой промежуток по времени событий;\n"
        "- решения по gate этого хода — строка на задачу: что решил оператор и что ты "
        "запустил; gate без ответа — списком «ждут решения»;\n"
        "- новая задача (task.created) — короткой карточкой: название, проект, роль "
        "оператора из строки «Роль оператора:», дедлайн если есть, ссылка, тег; "
        "маркеры [[FILE: …]] из уведомления — в начале карточки, каждый на своей строке;\n"
        "- остальное — строка на задачу; устаревшее не пересказывай как новость.\n"
        "Адреса не выдумывай: нет строки — нет ссылки. [[SILENT]] не пиши: если "
        "решать нечего, дайджест всё равно нужен."
    )
    return "\n\n".join(parts)
