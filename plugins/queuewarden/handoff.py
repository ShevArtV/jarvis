"""Дайджест QW → основной диалог Тимлида.

Разовый сеанс пишет дайджест оператору и закрывается — диалог Тимлида его не
видит. Поэтому готовый текст ставится вторым триггером в обычный путь топика:
Тимлид знает, что ушло оператору, и сам делает то, что ему разрешено без
решения оператора. Делать нечего — молчит.
"""

from __future__ import annotations

from bot.delivery import SILENT_MARKER

HANDOFF_SOURCE = "queuewarden_digest"


def build_handoff_prompt(texts: list[str]) -> str:
    digests = "\n\n---\n\n".join(t.strip() for t in texts if t and t.strip())
    return (
        "[Дайджест уведомлений QueueWarden — только что ушёл оператору в этот топик.]\n\n"
        f"{digests}\n\n"
        "---\n"
        "Это не сообщение оператора, а передача дайджеста в твой диалог. "
        "По каждой задаче сделай сам то, что по твоим правилам не требует решения "
        "оператора: сверить состояние в QW, проверить результат, прокомментировать, "
        "запустить следующую по «Очереди фокуса». Решения оператора (принять план, "
        "gate, прод, приёмка) за него не принимай и дайджест не пересказывай — "
        "он его уже видит. Если что-то сделал или нашёл, чего нет в дайджесте, — "
        "коротко отчитайся. Если делать нечего — ответь ровно "
        f"{SILENT_MARKER} и больше ничего."
    )
